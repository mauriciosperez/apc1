#include <stdio.h>

int main() {
    // == igualdade
    // != diferença
    // < menor
    // <= menor ou igual
    // > maior
    // >= maior ou igual

    printf("2==5? %i\n", 2==5);
    printf("2!=5? %i\n", 2!=5);
    printf("2<5? %i\n", 2<5);
    printf("2<=5? %i\n", 2<=5);
    printf("2>5? %i\n", 2>5);
    printf("2>=5? %i\n", 2>=5);

    return 0;
}
